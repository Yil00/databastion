#!/usr/bin/env bash
# Writes the built-in name lists of ADR-0049 decision 8 for one PostgreSQL major version, from a
# fresh server with no extension created (initdb's own `plpgsql` aside):
#
#   <major>/functions.txt   every `proname` of `pg_proc` in `pg_catalog`, and every function of
#                           `information_schema` as `information_schema.<name>`
#   <major>/operators.txt   every `oprname` of `pg_operator` in `pg_catalog`
#   <major>/types.txt       every `typname` of `pg_type` in `pg_catalog`, and every type of
#                           `information_schema` as `information_schema.<name>`
#   <major>/keywords.txt    `pg_get_keywords()`: each keyword and its category (U unreserved,
#                           C column name, T type or function name, R reserved), from which the
#                           connector tells the grammar's parenthesized forms (`COALESCE (`,
#                           `IN (`, `numeric (`) and the SQL type spellings (`integer`,
#                           `double precision`) from calls of functions and types
#
# Each list is sorted by byte value, one name per line, after `#` header lines that record the
# server version and the source (image reference with its digest, or the local cluster). The
# connector embeds the lists (`src/audit/builtins.rs`); the drift test of `src/it.rs` compares
# them with the catalogs of every engine-matrix image, both ways.
#
#   builtins/generate.sh image <image@sha256:digest>   # docker: run the image, extract, remove it
#   builtins/generate.sh psql <conninfo> <label>       # an existing fresh server (e.g. initdb)
#
# Dev tooling only; never run by the agent.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"

extract() {
  # $1: a psql command prefix (array name), $2: source label.
  local -n run=$1
  local label=$2
  local version major out
  version="$("${run[@]}" -c 'SHOW server_version')"
  version="${version%% *}"
  major="$("${run[@]}" -c "SELECT current_setting('server_version_num')::int / 10000")"
  out="$HERE/$major"
  mkdir -p "$out"
  local header="# PostgreSQL $version, $label. Generated by builtins/generate.sh; do not edit."
  {
    echo "$header"
    "${run[@]}" -c "SELECT n FROM (SELECT p.proname::text AS n FROM pg_catalog.pg_proc p
      WHERE p.pronamespace = 'pg_catalog'::regnamespace
      UNION SELECT 'information_schema.' || p.proname FROM pg_catalog.pg_proc p
      WHERE p.pronamespace = 'information_schema'::regnamespace) s
      ORDER BY n COLLATE \"C\""
  } >"$out/functions.txt"
  {
    echo "$header"
    "${run[@]}" -c "SELECT n FROM (SELECT DISTINCT o.oprname::text AS n FROM pg_catalog.pg_operator o
      WHERE o.oprnamespace = 'pg_catalog'::regnamespace) s ORDER BY n COLLATE \"C\""
  } >"$out/operators.txt"
  {
    echo "$header"
    "${run[@]}" -c "SELECT n FROM (SELECT t.typname::text AS n FROM pg_catalog.pg_type t
      WHERE t.typnamespace = 'pg_catalog'::regnamespace
      UNION SELECT 'information_schema.' || t.typname FROM pg_catalog.pg_type t
      WHERE t.typnamespace = 'information_schema'::regnamespace) s
      ORDER BY n COLLATE \"C\""
  } >"$out/types.txt"
  {
    echo "$header"
    "${run[@]}" -c "SELECT word || ' ' || catcode::text FROM pg_catalog.pg_get_keywords()
      ORDER BY word COLLATE \"C\""
  } >"$out/keywords.txt"
  # A fresh server: no extension but initdb's plpgsql.
  local extensions
  extensions="$("${run[@]}" -c "SELECT count(*) FROM pg_catalog.pg_extension
    WHERE extname <> 'plpgsql'")"
  if [ "$extensions" != 0 ]; then
    echo "error: the server has extensions other than plpgsql; use a fresh server" >&2
    exit 1
  fi
  echo "wrote $out (PostgreSQL $version)"
}

case "${1:-}" in
  image)
    image="${2:?image reference with digest}"
    case "$image" in *@sha256:*) ;; *) echo "error: pin the image by digest" >&2; exit 2 ;; esac
    name="databastion-builtins-$$"
    docker run -d --rm --network none --name "$name" -e POSTGRES_PASSWORD=builtins-only "$image" >/dev/null
    trap 'docker rm -f "$name" >/dev/null 2>&1 || true' EXIT
    for _ in $(seq 1 60); do
      if docker exec "$name" pg_isready -U postgres -q 2>/dev/null; then break; fi
      sleep 1
    done
    sleep 2
    # shellcheck disable=SC2034 # used through a nameref
    cmd=(docker exec "$name" psql -U postgres -d template1 -XAtq -v ON_ERROR_STOP=1)
    extract cmd "image $image"
    ;;
  psql)
    conninfo="${2:?conninfo}"
    label="${3:?source label}"
    # shellcheck disable=SC2034 # used through a nameref
    cmd=(psql "$conninfo" -XAtq -v ON_ERROR_STOP=1)
    extract cmd "$label"
    ;;
  *)
    echo "usage: $0 image <image@sha256:digest> | psql <conninfo> <label>" >&2
    exit 2
    ;;
esac
